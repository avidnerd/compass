type Run = { x: number; y: number; w: number }

const RUNS: Record<string, Run[]> = {}

function runs(name: string): Run[] {
  const cached = RUNS[name]
  if (cached) return cached
  const rows = G[name] ?? G.file
  const out: Run[] = []
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      if (row[x] === '#') {
        let w = 1
        while (row[x + w] === '#') w += 1
        out.push({ x, y, w })
        x += w
      } else x += 1
    }
  })
  RUNS[name] = out
  return out
}

